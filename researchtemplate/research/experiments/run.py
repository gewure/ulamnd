#!/usr/bin/env python3
"""Run the claim suite and write REPORT.md and results.json.

    python3 research/experiments/run.py            # fast mode, must stay in the minutes
    python3 research/experiments/run.py --full     # the long scales; each claim states its runtime
    python3 research/experiments/run.py --only T1,T3

The report is generated, never edited by hand: it is the evidence for CONCLUSIONS.md, and anything
written there must be traceable to a line in it. Re-run it whenever a number in any document is quoted
from it; if a number moved, that is the day's work.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
import traceback
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))  # so tests can import `lib`

import claims as claims_mod  # noqa: E402

ERROR = "ERROR"


def revision() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE,
                             capture_output=True, text=True, timeout=10)
        rev = out.stdout.strip() or "unversioned"
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=HERE,
                               capture_output=True, text=True, timeout=10).stdout.strip()
        return rev + ("+dirty" if dirty else "")
    except Exception:
        return "unversioned"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--full", action="store_true", help="run at the long scales")
    ap.add_argument("--only", default="", help="comma-separated claim keys")
    args = ap.parse_args()

    selected = [k.strip() for k in args.only.split(",") if k.strip()] or list(claims_mod.CLAIMS)
    unknown = [k for k in selected if k not in claims_mod.CLAIMS]
    if unknown:
        print(f"unknown claims: {', '.join(unknown)}", file=sys.stderr)
        return 2

    mode = "full" if args.full else "fast"
    started = datetime.now(timezone.utc)
    rev = revision()
    results = []

    for key in selected:
        c = claims_mod.CLAIMS[key]
        print(f"[{key}] {c.statement[:78]}", flush=True)
        t0 = time.perf_counter()
        try:
            v = c.fn(args.full)
            row = {"verdict": v.verdict, "summary": v.summary, "numbers": v.numbers, "notes": v.notes}
        except Exception:
            row = {"verdict": ERROR, "summary": "the test raised", "numbers": {},
                   "notes": traceback.format_exc()}
        row.update(key=key, statement=c.statement, refuted_if=c.refuted_if,
                   declared_runtime=c.runtime, seconds=round(time.perf_counter() - t0, 3))
        results.append(row)
        print(f"     -> {row['verdict']}: {row['summary']}  ({row['seconds']} s)", flush=True)

    payload = {
        "generated": started.isoformat(timespec="seconds"),
        "mode": mode,
        "revision": rev,
        "seed": getattr(claims_mod, "SEED", None),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "results": results,
    }
    out_json = HERE / ("results-full.json" if args.full else "results.json")
    out_json.write_text(json.dumps(payload, indent=2, default=str) + "\n")

    report = HERE / ("REPORT-full.md" if args.full else "REPORT.md")
    report.write_text(render(payload))

    counts: dict[str, int] = {}
    for r in results:
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    print("\n" + "  ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    print(f"wrote {report.name} and {out_json.name} (revision {rev}, mode {mode})")
    if counts.get(ERROR):
        return 1
    return 0


def render(p: dict) -> str:
    L = [f"# Experiment report ({p['mode']} mode)", "",
         "*Generated by `research/experiments/run.py`. Do not edit: re-run it. The human reading of this "
         "report is `CONCLUSIONS.md`.*", "",
         f"- generated: {p['generated']}",
         f"- revision: `{p['revision']}`",
         f"- seed: `{p['seed']}`",
         f"- python {p['python']} on {p['platform']}", "",
         "| claim | verdict | what decides it |", "|---|---|---|"]
    for r in p["results"]:
        L.append(f"| {r['key']} | **{r['verdict']}** | {r['summary']} |")
    L += ["", "---", ""]
    for r in p["results"]:
        L += [f"## {r['key']} — {r['verdict']}", "",
              f"**Claim.** {r['statement']}", "",
              f"**Refuted if.** {r['refuted_if']}", "",
              f"**Result.** {r['summary']}", ""]
        if r["numbers"]:
            L += ["```json", json.dumps(r["numbers"], indent=2, default=str), "```", ""]
        if r["notes"]:
            L += [f"**Notes.** {r['notes']}", ""]
        L += [f"*(declared runtime {r['declared_runtime']}; this run {r['seconds']} s)*", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
